def E(s): return html.escape(str(s), quote=True)
def rect(x, y, w, h, f='w', st='k', sw=2, rx=0, extra=''):
    return '<rect x="%g" y="%g" width="%g" height="%g" fill="%s" stroke="%s" stroke-width="%g" rx="%g"%s/>' % (x, y, w, h, C.get(f, f), C.get(st, st) if st else 'none', sw if st else 0, rx, extra)
def box(x, y, w, h, f='S', st='k', rx=6): return rect(x, y, w, h, f, st, 2, rx)
def tx(x, y, s, size=17, f='k', a='middle', wt=700):
    return '<text x="%g" y="%g" font-size="%g" fill="%s" text-anchor="%s" font-weight="%d">%s</text>' % (x, y, size, C.get(f, f), a, wt, E(s))
def ln(x1, y1, x2, y2, f='k', sw=2, dash=''):
    return '<line x1="%g" y1="%g" x2="%g" y2="%g" stroke="%s" stroke-width="%g"%s/>' % (x1, y1, x2, y2, C.get(f, f), sw, (' stroke-dasharray="%s"' % dash) if dash else '')
def arrow(x1, y1, x2, y2, f='k', sw=3):
    import math
    a = math.atan2(y2 - y1, x2 - x1); L = 10
    p1 = (x2 - L * math.cos(a - .5), y2 - L * math.sin(a - .5)); p2 = (x2 - L * math.cos(a + .5), y2 - L * math.sin(a + .5))
    return ln(x1, y1, x2, y2, f, sw) + '<polygon points="%g,%g %g,%g %g,%g" fill="%s"/>' % (x2, y2, p1[0], p1[1], p2[0], p2[1], C.get(f, f))
def dot(x, y, f='b', s=10, shape='sq'):
    if shape == 'tri': return '<polygon points="%g,%g %g,%g %g,%g" fill="%s" stroke="#16212b" stroke-width="1.5"/>' % (x, y - s * .7, x - s * .7, y + s * .5, x + s * .7, y + s * .5, C.get(f, f))
    return rect(x - s / 2, y - s / 2, s, s, f, 'k', 1.5)
def circ(x, y, r, f='none', st='k', sw=2, dash=''):
    return '<circle cx="%g" cy="%g" r="%g" fill="%s" stroke="%s" stroke-width="%g"%s/>' % (x, y, r, C.get(f, f), C.get(st, st), sw, (' stroke-dasharray="%s"' % dash) if dash else '')
def path(d, f='none', st='k', sw=3): return '<path d="%s" fill="%s" stroke="%s" stroke-width="%g" stroke-linejoin="round" stroke-linecap="round"/>' % (d, C.get(f, f), C.get(st, st), sw)
def pix(name, x, y, s=3, col='b', flip=False):
    out = []
    for j, row in enumerate(ICON[name]):
        row = row[::-1] if flip else row
        i = 0
        while i < len(row):
            ch = row[i]
            if ch == '.': i += 1; continue
            k = i
            while k < len(row) and row[k] == ch: k += 1
            fill = C[col] if ch == 'x' else C[ch]
            out.append('<rect x="%g" y="%g" width="%g" height="%g" fill="%s"/>' % (x + i * s, y + j * s, (k - i) * s, s, fill))
            i = k
    return ''.join(out)
def badge(x, y, n): return rect(x - 12, y - 12, 24, 24, 'a', 'k', 2, 3) + tx(x, y + 6, n, 16, 'w')
def ok(x, y, s=1, f='g'): return path('M%g %g l%g %g l%g %g' % (x - 8 * s, y, 6 * s, 7 * s, 11 * s, -14 * s), 'none', f, 4 * s)
def no(x, y, s=1, f='r'): return path('M%g %g l%g %g M%g %g l%g %g' % (x - 7 * s, y - 7 * s, 14 * s, 14 * s, x + 7 * s, y - 7 * s, -14 * s, 14 * s), 'none', f, 4 * s)
def axes(x, y, w, h, xl='', yl=''):
    return ln(x, y + h, x + w, y + h, 'k', 2) + ln(x, y, x, y + h, 'k', 2) + (tx(x + w, y + h + 18, xl, 13, 'm', 'end', 500) if xl else '') + (tx(x + 4, y - 6, yl, 13, 'm', 'start', 500) if yl else '')
def svg(inner): return '<svg viewBox="0 0 %d %d" class="picsvg" xmlns="http://www.w3.org/2000/svg" font-family="IBM Plex Sans KR, Apple SD Gothic Neo, Malgun Gothic, sans-serif">%s%s</svg>' % (W, H, rect(1, 1, W - 2, H - 2, 'w', 'l', 2, 10), inner)

import random
def cloud(cx, cy, n, sd, col, seed, shape='sq', s=9):
    rnd = random.Random(seed); return ''.join(dot(cx + rnd.gauss(0, sd), cy + rnd.gauss(0, sd * .8), col, s, shape) for _ in range(n))

